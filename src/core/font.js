const Font = (() => {
  const CW = 6, LH = 10;
  const glyphs = {};
  for (const ch in FONT_GLYPHS) {
    glyphs[ch] = FONT_GLYPHS[ch].split('|').map((r) => r.split('').map((c) => c === '#'));
  }
  const fallback = glyphs['?'];
  // one white glyph sheet; colored sheets are cached per color
  const chars = Object.keys(glyphs);
  const index = {}; chars.forEach((c, i) => { index[c] = i; });
  const sheets = {};

  function sheet(color) {
    const key = typeof color === 'string' ? color : color.join(',');
    if (sheets[key]) return sheets[key];
    const cv = document.createElement('canvas');
    cv.width = chars.length * CW; cv.height = LH;
    const ctx = cv.getContext('2d');
    const img = ctx.createImageData(cv.width, cv.height);
    const c = hex(color);
    chars.forEach((ch, i) => {
      const g = glyphs[ch];
      for (let y = 0; y < g.length; y++) for (let x = 0; x < 5; x++) {
        if (g[y][x]) {
          const o = ((y + 1) * cv.width + i * CW + x) * 4;
          img.data[o] = c[0]; img.data[o + 1] = c[1]; img.data[o + 2] = c[2]; img.data[o + 3] = c[3] == null ? 255 : c[3];
        }
      }
    });
    ctx.putImageData(img, 0, 0);
    sheets[key] = cv;
    return cv;
  }

  // Draw text. opts: {shadow, wobble(seed), scale, max}
  function draw(ctx, text, x, y, color, opts) {
    opts = opts || {};
    const sc = opts.scale || 1;
    const sh = sheet(color || '#fff');
    const shadow = opts.shadow ? sheet(opts.shadow === true ? '#000' : opts.shadow) : null;
    text = String(text);
    const n = opts.max != null ? Math.min(text.length, opts.max) : text.length;
    let cx = x;
    for (let i = 0; i < n; i++) {
      const ch = text[i];
      let gi = index[ch];
      if (gi === undefined) gi = index[ch.toUpperCase()] !== undefined ? index[ch.toUpperCase()] : index['?'];
      let dy = 0, dx = 0;
      if (opts.wobble) {
        const h = Math.sin((i + 1) * 12.9898 + opts.wobble * 78.233) * 43758.5453;
        const f = h - Math.floor(h);
        dy = f < 0.25 ? -1 : f > 0.8 ? 1 : 0;
        dx = f > 0.92 ? 1 : 0;
      }
      if (ch !== ' ') {
        if (shadow) ctx.drawImage(shadow, gi * CW, 0, CW, LH, cx + sc + dx * sc, y + sc + dy * sc, CW * sc, LH * sc);
        ctx.drawImage(sh, gi * CW, 0, CW, LH, cx + dx * sc, y + dy * sc, CW * sc, LH * sc);
      }
      cx += CW * sc;
    }
    return cx;
  }
  function width(text, scale) { return String(text).length * CW * (scale || 1); }
  function center(ctx, text, cx, y, color, opts) {
    const w = width(text, opts && opts.scale);
    draw(ctx, text, Math.round(cx - w / 2), y, color, opts);
  }
  // Paint into a Pix buffer (used for signs / documents baked into textures)
  function paint(pix, text, x, y, color, scale) {
    scale = scale || 1;
    const c = hex(color);
    let cx = x;
    for (const ch of String(text)) {
      const g = glyphs[ch] || glyphs[ch.toUpperCase()] || fallback;
      for (let gy = 0; gy < g.length; gy++) for (let gx = 0; gx < 5; gx++) {
        if (g[gy][gx]) pix.rect(cx + gx * scale, y + gy * scale, scale, scale, c);
      }
      cx += CW * scale;
    }
    return cx;
  }
  return { draw, width, center, paint, CW, LH, glyphs };
})();
